/** Saved choice first; otherwise Vietnamese for a Vietnamese browser and English for everything else. */
export function detectLang(saved, navigatorLang) {
  if (LANGS.includes(saved)) return saved;
  if (!navigatorLang) return "vi";
  return String(navigatorLang).toLowerCase().startsWith("vi") ? "vi" : "en";
}

let current = "vi";
export const getLang = () => current;
export function setLangState(lang) { if (LANGS.includes(lang)) current = lang; }

/** Translate a key. Falls back to Vietnamese, then to the key itself, so a missing English string never blanks the page. */
export function t(key, params = {}) {
  const v = DICT[current]?.[key] ?? DICT.vi[key];
  if (v === undefined) return key;
  if (typeof v === "function") return v(params);
  return v.replace(/\{(\w+)\}/g, (_, k) => (params[k] === undefined ? `{${k}}` : String(params[k])));
}
